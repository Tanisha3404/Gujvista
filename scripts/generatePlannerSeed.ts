// Generates supabase/seed_planner.sql from src/data/itineraries.ts.
// Run from the project root:  npx tsx scripts/generatePlannerSeed.ts
import { mkdirSync, writeFileSync } from 'node:fs'
import { destinationSeed } from '../src/data/destinations'
import { itinerarySeed } from '../src/data/itineraries'

const str = (value: string): string => `'${value.replace(/'/g, "''")}'`
const strOrNull = (value: string | null | undefined): string => (value ? str(value) : 'null')

// Catch typos before they reach the database.
const knownSlugs = new Set(destinationSeed.map((destination) => destination.slug))
for (const itinerary of itinerarySeed) {
  for (const stop of itinerary.stops) {
    if (!knownSlugs.has(stop.destinationSlug)) {
      throw new Error(`Unknown destination "${stop.destinationSlug}" in "${itinerary.slug}"`)
    }
    if (stop.day < 1 || stop.day > itinerary.durationDays) {
      throw new Error(`Day ${stop.day} is outside the ${itinerary.durationDays}-day trip "${itinerary.slug}"`)
    }
  }
}

const itineraryRows = itinerarySeed.map(
  (i) =>
    `  (${str(i.slug)}, ${str(i.title)}, ${str(i.description)}, ${i.durationDays}, ${strOrNull(i.coverImage)})`,
)

const slugList = itinerarySeed.map((i) => str(i.slug)).join(', ')

const stopRows = itinerarySeed.flatMap((i) =>
  i.stops.map(
    (stop) =>
      `  ((select id from public.itineraries where slug = ${str(i.slug)}), (select id from public.destinations where slug = ${str(stop.destinationSlug)}), ${stop.day}, ${stop.sequence}, ${str(stop.description)})`,
  ),
)

const sql = `-- GENERATED by scripts/generatePlannerSeed.ts. Do not edit by hand.
-- Safe to re-run: itineraries are updated by slug and their stops are replaced.
-- Run it in the Supabase SQL Editor AFTER seed.sql (it needs the destinations).

insert into public.itineraries (slug, title, description, duration_days, cover_image)
values
${itineraryRows.join(',\n')}
on conflict (slug) do update set
  title = excluded.title,
  description = excluded.description,
  duration_days = excluded.duration_days,
  cover_image = excluded.cover_image;

delete from public.itinerary_items
where itinerary_id in (select id from public.itineraries where slug in (${slugList}));

insert into public.itinerary_items (itinerary_id, destination_id, day_number, sequence_number, description)
values
${stopRows.join(',\n')};
`

mkdirSync('supabase', { recursive: true })
writeFileSync('supabase/seed_planner.sql', sql)

console.log(`Wrote supabase/seed_planner.sql (${itinerarySeed.length} itineraries, ${stopRows.length} stops)`)