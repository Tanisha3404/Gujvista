// This script generates a SQL file that can be run in the Supabase SQL Editor to seed the database with categories, destinations & blog posts
import { mkdirSync, writeFileSync } from 'node:fs'
import { blogPostSeed } from '../src/data/blogPosts'
import { categorySeed } from '../src/data/categories'
import { destinationSeed } from '../src/data/destinations'

// the first six destinations are the homepage's "Top Destinations"
const HIDDEN_GEM_SLUGS = [
  'polo-forest',
  'zarwani-waterfall',
  'dholavira',
  'velavadar-blackbuck-national-park',
]
// the first six destinations are the homepage's "Top Destinations"
const FEATURED_COUNT = 6

// helper functions to generate SQL values
const str = (value: string): string => `'${value.replace(/'/g, "''")}'`
const strOrNull = (value: string | null | undefined): string => (value ? str(value) : 'null')
const textArray = (items: string[] | undefined): string =>
  items && items.length > 0 ? `array[${items.map(str).join(', ')}]::text[]` : `'{}'::text[]`

const categorySlugById = new Map(categorySeed.map((category) => [category.id, category.slug]))

const categoryRows = categorySeed.map(
  (c, index) =>
    `  (${str(c.name)}, ${str(c.slug)}, ${str(c.description)}, ${strOrNull(c.image)}, ${index})`,
)

const destinationRows = destinationSeed.map((d, index) => {
  const categorySlug = categorySlugById.get(d.categoryId)
  if (!categorySlug) throw new Error(`Unknown category "${d.categoryId}" for ${d.slug}`)

  const values = [
    str(d.name),
    str(d.slug),
    str(d.district),
    `(select id from public.categories where slug = ${str(categorySlug)})`,
    str(d.shortDescription),
    str(d.fullDescription),
    strOrNull(d.mainImage),
    str(d.bestTimeToVisit),
    String(d.latitude),
    String(d.longitude),
    str(d.travelTips),
    str(d.historicalSignificance),
    textArray(d.majorAttractions),
    textArray(d.thingsToDo),
    String(index < FEATURED_COUNT),
    String(HIDDEN_GEM_SLUGS.includes(d.slug)),
    String(index),
  ]
  return `  (${values.join(', ')})`
})

const postRows = blogPostSeed.map((p) => {
  const values = [
    str(p.title),
    str(p.slug),
    str(p.excerpt),
    str(p.content),
    strOrNull(p.coverImage),
    `${str(`${p.publishedAt}T00:00:00Z`)}::timestamptz`,
    str(p.status),
  ]
  return `  (${values.join(', ')})`
})

const sql = `-- GENERATED by scripts/generateSeed.ts. Do not edit by hand.
-- Re-running this file updates existing rows (matched by slug); it does not duplicate them.
-- Run it in the Supabase SQL Editor.

-- Categories
insert into public.categories (name, slug, description, image, sort_order)
values
${categoryRows.join(',\n')}
on conflict (slug) do update set
  name = excluded.name,
  description = excluded.description,
  image = excluded.image,
  sort_order = excluded.sort_order;

-- Destinations
insert into public.destinations (
  name, slug, district, category_id, short_description, full_description,
  main_image, best_time_to_visit, latitude, longitude, travel_tips,
  historical_significance, major_attractions, things_to_do, is_featured, is_hidden_gem,
  sort_order
)
values
${destinationRows.join(',\n')}
on conflict (slug) do update set
  name = excluded.name,
  district = excluded.district,
  category_id = excluded.category_id,
  short_description = excluded.short_description,
  full_description = excluded.full_description,
  main_image = excluded.main_image,
  best_time_to_visit = excluded.best_time_to_visit,
  latitude = excluded.latitude,
  longitude = excluded.longitude,
  travel_tips = excluded.travel_tips,
  historical_significance = excluded.historical_significance,
  major_attractions = excluded.major_attractions,
  things_to_do = excluded.things_to_do,
  is_featured = excluded.is_featured,
  is_hidden_gem = excluded.is_hidden_gem,
  sort_order = excluded.sort_order;

-- Travel guides
insert into public.blog_posts (title, slug, excerpt, content, cover_image, published_at, status)
values
${postRows.join(',\n')}
on conflict (slug) do update set
  title = excluded.title,
  excerpt = excluded.excerpt,
  content = excluded.content,
  cover_image = excluded.cover_image,
  published_at = excluded.published_at,
  status = excluded.status;
`

mkdirSync('supabase', { recursive: true })
writeFileSync('supabase/seed.sql', sql)

console.log(
  `Wrote supabase/seed.sql (${categorySeed.length} categories, ${destinationSeed.length} destinations, ${blogPostSeed.length} posts)`,
)